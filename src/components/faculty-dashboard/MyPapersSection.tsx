import { CalendarClock, Eye, FolderOpen, Loader2, X } from 'lucide-react';
import { useEffect, useState } from 'react';
import { API_CONFIG } from '../../utils/constants';
import SectionHeader from './SectionHeader';

type Paper = {
  paper_id: number;
  title: string;
  generated_at: string | null;
  branch: string;
  semester: string | number;
  questions: number;
  marks: number;
  status: string;
};

type PaperDetails = Paper & {
  paper_information: {
    subject?: string;
    branch?: string;
    semester?: string | number;
    exam_type?: string;
  };
  sections: Record<string, {
    questions_to_attempt?: number;
    questions: Array<{ question_text: string; marks?: number }>;
  }>;
};

const formatDate = (value: string | null) => {
  if (!value) return 'Unknown date';
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? value : date.toLocaleString();
};

export default function MyPapersSection() {
  const [papers, setPapers] = useState<Paper[]>([]);
  const [selectedPaper, setSelectedPaper] = useState<PaperDetails | null>(null);
  const [loading, setLoading] = useState(true);
  const [opening, setOpening] = useState<number | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    const controller = new AbortController();
    const loadPapers = async () => {
      try {
        const token = sessionStorage.getItem('authToken') || sessionStorage.getItem('adminToken');
        const response = await fetch(`${API_CONFIG.BACKEND_URL}/api/generated-papers`, {
          headers: token ? { Authorization: 'Bearer ' + token } : {},
          signal: controller.signal,
        });
        const result = await response.json();
        if (!response.ok) throw new Error(result.error || 'Unable to load generated papers.');
        setPapers(Array.isArray(result.papers) ? result.papers : []);
      } catch (loadError) {
        if (!controller.signal.aborted) setError(loadError instanceof Error ? loadError.message : 'Unable to load generated papers.');
      } finally {
        if (!controller.signal.aborted) setLoading(false);
      }
    };
    void loadPapers();
    return () => controller.abort();
  }, []);

  const viewPaper = async (paperId: number) => {
    setOpening(paperId);
    setError(null);
    try {
      const token = sessionStorage.getItem('authToken') || sessionStorage.getItem('adminToken');
      const response = await fetch(`${API_CONFIG.BACKEND_URL}/api/generated-papers/${paperId}`, {
        headers: token ? { Authorization: 'Bearer ' + token } : {},
      });
      const result = await response.json();
      if (!response.ok || !result.paper) throw new Error(result.error || 'Unable to open paper.');
      setSelectedPaper({ ...result.paper, ...papers.find((paper) => paper.paper_id === paperId) });
    } catch (viewError) {
      setError(viewError instanceof Error ? viewError.message : 'Unable to open paper.');
    } finally {
      setOpening(null);
    }
  };

  return (
    <section id="my-papers" className="px-4 pb-8 md:px-8">
      <SectionHeader title="My Papers" subtitle="View question papers generated by AI." icon={FolderOpen} />
      {loading && <p className="flex items-center gap-2 text-sm text-slate-600"><Loader2 className="h-4 w-4 animate-spin" /> Loading generated papers...</p>}
      {error && <p className="text-sm font-medium text-red-700">{error}</p>}
      {!loading && !error && papers.length === 0 && <p className="rounded-2xl border border-dashed border-slate-300 bg-white/50 p-6 text-sm text-slate-600">No generated papers yet.</p>}
      <div className="mb-6 grid gap-4 md:grid-cols-3">
        {papers.map((paper) => (
          <div key={paper.paper_id} className="rounded-2xl border border-white/60 bg-white/70 p-4 shadow-sm">
            <div className="flex items-start justify-between gap-3">
              <p className="text-sm font-semibold text-slate-800">{paper.title}</p>
              <button type="button" onClick={() => void viewPaper(paper.paper_id)} disabled={opening === paper.paper_id} className="inline-flex items-center gap-1 rounded-lg border border-white/60 bg-white px-2 py-1 text-[11px] font-semibold text-slate-700">
                {opening === paper.paper_id ? <Loader2 className="h-3.5 w-3.5 animate-spin" /> : <Eye className="h-3.5 w-3.5" />}
                {opening === paper.paper_id ? 'Opening...' : 'View'}
              </button>
            </div>
            <div className="mt-3 flex flex-wrap gap-2 text-[11px] text-slate-600">
              <span className="rounded-full bg-orange-100 px-2 py-1 font-semibold text-orange-700">{paper.marks} Marks</span>
              <span className="rounded-full bg-amber-100 px-2 py-1 font-semibold text-amber-700">{paper.questions} Questions</span>
              <span className="rounded-full border border-amber-200 bg-white px-2 py-1">Semester {paper.semester}</span>
            </div>
            <p className="mt-3 inline-flex items-center gap-1 text-xs text-slate-500"><CalendarClock className="h-3.5 w-3.5" /> Generated {formatDate(paper.generated_at)}</p>
          </div>
        ))}
      </div>
      {selectedPaper && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-950/50 p-4" role="dialog" aria-modal="true">
          <div className="max-h-[90vh] w-full max-w-4xl overflow-y-auto rounded-2xl bg-white p-6 shadow-2xl">
            <div className="flex items-start justify-between border-b border-slate-200 pb-4">
              <div>
                <h2 className="text-xl font-bold text-slate-800">{selectedPaper.paper_information.subject || selectedPaper.title}</h2>
                <p className="mt-1 text-sm text-slate-600">{selectedPaper.paper_information.branch} · Semester {selectedPaper.paper_information.semester} · {selectedPaper.paper_information.exam_type}</p>
              </div>
              <button type="button" onClick={() => setSelectedPaper(null)} aria-label="Close paper preview"><X className="h-5 w-5 text-slate-500" /></button>
            </div>
            <div className="mt-5 space-y-5">
              {Object.entries(selectedPaper.sections || {}).map(([name, section]) => (
                <section key={name}>
                  <div className="mb-2 flex justify-between"><h3 className="font-bold text-slate-800">{name}</h3><span className="text-xs text-slate-500">Attempt {section.questions_to_attempt ?? '-'}</span></div>
                  <ol className="space-y-2">
                    {section.questions.map((question, index) => <li key={`${name}-${index}`} className="rounded-lg border border-slate-200 bg-slate-50 p-3 text-sm text-slate-700"><span className="mr-2 font-semibold">{index + 1}.</span>{question.question_text}{question.marks !== undefined && <span className="float-right text-slate-500">{question.marks} marks</span>}</li>)}
                  </ol>
                </section>
              ))}
            </div>
          </div>
        </div>
      )}
    </section>
  );
}
