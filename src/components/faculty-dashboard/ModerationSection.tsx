import { useEffect, useState } from 'react';
import { ClipboardCheck, LoaderCircle } from 'lucide-react';
import SectionHeader from './SectionHeader';
import { API_CONFIG } from '../../utils/constants';

type ModerationPaper = {
  paper_id: number;
  subject_name: string;
  subject_code: string;
  branch: string;
  semester: string | number;
  exam_type: string;
  exam_year?: number | null;
  created_at: string;
  generated_by_name: string;
  sections: Record<string, { questions?: Array<{ question_text?: string; marks?: number }> }>;
};

type ApiResponse = {
  success: boolean;
  message?: string;
  papers?: ModerationPaper[];
};

export default function ModerationSection() {
  const [papers, setPapers] = useState<ModerationPaper[]>([]);
  const [selectedPaper, setSelectedPaper] = useState<ModerationPaper | null>(null);
  const [comment, setComment] = useState('');
  const [loading, setLoading] = useState(true);
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [notice, setNotice] = useState<string | null>(null);

  const loadPapers = async () => {
    setLoading(true);
    setError(null);
    try {
      const token = sessionStorage.getItem('authToken');
      if (!token) throw new Error('Your faculty session has expired. Please sign in again.');
      const response = await fetch(`${API_CONFIG.BACKEND_URL}/api/faculty/moderation/papers`, {
        headers: { Authorization: `Bearer ${token}` },
      });
      const data = await response.json() as ApiResponse;
      if (!response.ok || !data.success || !Array.isArray(data.papers)) {
        throw new Error(data.message || 'Unable to load papers for moderation.');
      }
      setPapers(data.papers);
    } catch (loadError) {
      setError(loadError instanceof Error ? loadError.message : 'Unable to load papers for moderation.');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => { void loadPapers(); }, []);

  const submitDecision = async (decision: 'approve' | 'request-changes') => {
    if (!selectedPaper) return;
    if (decision === 'request-changes' && !comment.trim()) {
      setError('Add a comment explaining the requested changes.');
      return;
    }
    setSaving(true);
    setError(null);
    setNotice(null);
    try {
      const token = sessionStorage.getItem('authToken');
      if (!token) throw new Error('Your faculty session has expired. Please sign in again.');
      const response = await fetch(
        `${API_CONFIG.BACKEND_URL}/api/faculty/moderation/papers/${selectedPaper.paper_id}/${decision}`,
        {
          method: 'POST',
          headers: {
            Authorization: `Bearer ${token}`,
            'Content-Type': 'application/json',
          },
          body: JSON.stringify({ comment }),
        },
      );
      const data = await response.json() as ApiResponse;
      if (!response.ok || !data.success) throw new Error(data.message || 'Unable to save moderation decision.');
      setNotice(decision === 'approve' ? 'Paper approved for admin review.' : 'Changes requested and comment sent to the setter.');
      setSelectedPaper(null);
      setComment('');
      await loadPapers();
    } catch (actionError) {
      setError(actionError instanceof Error ? actionError.message : 'Unable to save moderation decision.');
    } finally {
      setSaving(false);
    }
  };

  return (
    <section id="moderation" className="px-4 pb-8 md:px-8">
      <SectionHeader
        title="Moderation Queue"
        subtitle="Review database-backed papers assigned to you for moderation."
        icon={ClipboardCheck}
      />
      {error && <p role="alert" className="mb-4 rounded-xl border border-rose-200 bg-rose-50 px-4 py-3 text-sm text-rose-700">{error}</p>}
      {notice && <p role="status" className="mb-4 rounded-xl border border-emerald-200 bg-emerald-50 px-4 py-3 text-sm text-emerald-700">{notice}</p>}

      {loading ? (
        <div className="flex items-center justify-center gap-2 rounded-2xl bg-white/80 p-10 text-sm text-slate-500">
          <LoaderCircle className="h-4 w-4 animate-spin" /> Loading moderation queue...
        </div>
      ) : papers.length === 0 ? (
        <div className="rounded-2xl border border-dashed border-slate-300 bg-white/80 p-10 text-center">
          <p className="font-semibold text-slate-700">No papers awaiting moderation</p>
          <p className="mt-1 text-sm text-slate-500">Eligible papers from your assigned subjects will appear here.</p>
        </div>
      ) : (
        <div className="space-y-3">
          {papers.map(paper => (
            <article key={paper.paper_id} className="flex flex-wrap items-center justify-between gap-4 rounded-2xl border border-white/60 bg-white/80 p-5 shadow-sm">
              <div>
                <h3 className="font-semibold text-slate-800">{paper.subject_name}</h3>
                <p className="mt-1 text-sm text-slate-600">
                  Generated by: {paper.generated_by_name} · {paper.exam_type} {paper.exam_year || ''}
                </p>
                <p className="mt-1 text-xs text-slate-500">{paper.subject_code} · {paper.branch} · Semester {paper.semester}</p>
                <p className="mt-1 text-xs font-semibold text-amber-700">Awaiting Moderation</p>
              </div>
              <button type="button" onClick={() => { setSelectedPaper(paper); setComment(''); }} className="rounded-xl bg-amber-600 px-4 py-2 text-sm font-semibold text-white">
                View Paper
              </button>
            </article>
          ))}
        </div>
      )}

      {selectedPaper && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/40 p-4">
          <div role="dialog" aria-modal="true" aria-labelledby="moderation-paper-title" className="max-h-[90vh] w-full max-w-4xl overflow-y-auto rounded-2xl bg-white p-6 shadow-xl">
            <div className="flex items-start justify-between gap-4">
              <div>
                <h2 id="moderation-paper-title" className="text-xl font-bold text-slate-800">{selectedPaper.subject_name} — {selectedPaper.exam_type} {selectedPaper.exam_year || ''}</h2>
                <p className="mt-1 text-sm text-slate-500">Generated by {selectedPaper.generated_by_name}</p>
              </div>
              <button type="button" onClick={() => setSelectedPaper(null)} className="text-sm text-slate-500">Close</button>
            </div>
            <div className="mt-5 space-y-5">
              {Object.entries(selectedPaper.sections || {}).map(([section, data]) => (
                <div key={section}>
                  <h3 className="font-semibold text-slate-700">{section}</h3>
                  <ol className="mt-2 list-decimal space-y-2 pl-5 text-sm text-slate-700">
                    {(data.questions || []).map((question, index) => (
                      <li key={`${section}-${index}`}>{question.question_text || 'Question text unavailable'} <span className="text-slate-500">({question.marks ?? '—'} marks)</span></li>
                    ))}
                  </ol>
                </div>
              ))}
            </div>
            <label className="mt-5 block text-sm font-semibold text-slate-700">
              Feedback and requested changes
              <textarea value={comment} onChange={event => setComment(event.target.value)} rows={4} className="mt-2 w-full rounded-xl border border-slate-200 p-3 font-normal" placeholder="Required when requesting changes; optional when approving." />
            </label>
            <div className="mt-4 flex flex-wrap gap-3">
              <button type="button" onClick={() => void submitDecision('approve')} disabled={saving} className="rounded-xl bg-emerald-600 px-4 py-2.5 text-sm font-semibold text-white disabled:opacity-50">
                {saving ? 'Saving...' : 'Approve for Admin Review'}
              </button>
              <button type="button" onClick={() => void submitDecision('request-changes')} disabled={saving} className="rounded-xl bg-amber-600 px-4 py-2.5 text-sm font-semibold text-white disabled:opacity-50">
                Request Changes
              </button>
            </div>
          </div>
        </div>
      )}
    </section>
  );
}
